using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using Badger.Trek.Core.Providers;

namespace Badger.Trek.Providers.Oracle.Scripting;

/// <summary>A column as DDL writes it.</summary>
/// <param name="Name">Its name.</param>
/// <param name="Type">VARCHAR2(20 CHAR), NUMBER(12,2) ...</param>
/// <param name="Default">The default expression, or the expression of a virtual column; null when none.</param>
/// <param name="Nullable">False for NOT NULL.</param>
/// <param name="Virtual">A virtual column (GENERATED ALWAYS AS (Default) VIRTUAL).</param>
/// <param name="Identity">The identity clause (GENERATED BY DEFAULT AS IDENTITY ...), or null.</param>
/// <param name="DefaultOnNull">DEFAULT ON NULL.</param>
public sealed record OracleColumn(string Name, string Type, string? Default, bool Nullable, bool Virtual, string? Identity, bool DefaultOnNull)
{
    /// <summary>Everything but the name: two columns with the same Rest have the same definition.</summary>
    public string Rest => Virtual
        ? $"{Type} GENERATED ALWAYS AS ({Default}) VIRTUAL"
        : Type + (Identity is null ? string.Empty : " " + Identity)
          + (Default is null || Identity is not null ? string.Empty : $" DEFAULT{(DefaultOnNull ? " ON NULL" : string.Empty)} {Default}")
          + (Nullable || Identity is not null ? string.Empty : " NOT NULL");

    public string Definition => $"{OracleModel.Q(Name)} {Rest}";
}

/// <summary>A primary key, unique, foreign key or check constraint.</summary>
/// <param name="Name">The name it has in this database.</param>
/// <param name="Generated">Oracle made the name up (SYS_C...): compared by definition, scripted without a name.</param>
/// <param name="Kind">P, U, R or C.</param>
/// <param name="Body">PRIMARY KEY (...), UNIQUE (...), FOREIGN KEY (...) REFERENCES ..., CHECK (...)</param>
/// <param name="References">The referenced table of a foreign key.</param>
public sealed record OracleConstraint(string Name, bool Generated, string Kind, string Body, string? References)
{
    public bool ForeignKey => Kind == "R";

    /// <summary>What identifies it across databases: its name, or for a generated name, its definition.</summary>
    public string Identity => Generated ? "(" + Body + ")" : Name;

    public string Definition => Generated ? Body : $"CONSTRAINT {OracleModel.Q(Name)} {Body}";
}

/// <summary>An index that does not belong to a constraint.</summary>
public sealed record OracleIndex(string Name, string Create);

public sealed record OracleTable(string Name, string Prefix, IReadOnlyList<OracleColumn> Columns, IReadOnlyList<OracleConstraint> Constraints, IReadOnlyList<OracleIndex> Indexes, string? Comment, IReadOnlyDictionary<string, string> ColumnComments)
{
    /// <summary>CREATE TABLE with its columns, primary key, unique and check constraints; foreign keys come later.</summary>
    public string CreateWithoutForeignKeys()
    {
        var parts = Columns.Select(c => "  " + c.Definition)
            .Concat(Constraints.Where(c => !c.ForeignKey).Select(c => "  " + c.Definition));
        return $"CREATE {Prefix}TABLE {OracleModel.Q(Name)} (\n{string.Join(",\n", parts)}\n)";
    }
}

/// <summary>A view, sequence, synonym or PL/SQL object, with the statement that creates it.</summary>
/// <param name="Kind">view, sequence, synonym, type, type body, package, package body, function, procedure, trigger.</param>
/// <param name="Name">Its name.</param>
/// <param name="Create">The statement that creates it (CREATE OR REPLACE ... for code).</param>
/// <param name="Table">The table of a trigger.</param>
/// <param name="PlSql">Ends with a '/' line when scripted.</param>
public sealed record OracleObject(string Kind, string Name, string Create, string? Table = null, bool PlSql = false)
{
    public string Key => $"{Kind} {Name}";
}

/// <summary>
/// The deploy schema as a structured model, from the ALL_* dictionary views, for scripting differences: tables (columns,
/// constraints, indexes, comments), views, sequences, synonyms and PL/SQL source. trek's state tables, the recycle bin and
/// objects Oracle makes itself are left out; so is the schema's own name inside definitions.
/// </summary>
public sealed partial class OracleModel
{
    public Dictionary<string, OracleTable> Tables { get; } = new(StringComparer.Ordinal);

    public Dictionary<string, OracleObject> Objects { get; } = new(StringComparer.Ordinal);

    public List<string> Warnings { get; } = [];

    /// <summary>A name as DDL writes it: bare when Oracle would store it that way (upper case), quoted otherwise.</summary>
    public static string Q(string name) =>
        PlainNameRegex().IsMatch(name) && !Reserved.Contains(name) ? name : "\"" + name.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";

    private static readonly HashSet<string> Reserved = new(StringComparer.Ordinal)
    {
        "ACCESS", "ADD", "ALL", "ALTER", "AND", "ANY", "AS", "ASC", "AUDIT", "BETWEEN", "BY", "CHAR", "CHECK", "CLUSTER", "COLUMN", "COMMENT", "COMPRESS",
        "CONNECT", "CREATE", "CURRENT", "DATE", "DECIMAL", "DEFAULT", "DELETE", "DESC", "DISTINCT", "DROP", "ELSE", "EXCLUSIVE", "EXISTS", "FILE", "FLOAT",
        "FOR", "FROM", "GRANT", "GROUP", "HAVING", "IDENTIFIED", "IMMEDIATE", "IN", "INCREMENT", "INDEX", "INITIAL", "INSERT", "INTEGER", "INTERSECT", "INTO",
        "IS", "LEVEL", "LIKE", "LOCK", "LONG", "MAXEXTENTS", "MINUS", "MLSLABEL", "MODE", "MODIFY", "NOAUDIT", "NOCOMPRESS", "NOT", "NOWAIT", "NULL", "NUMBER",
        "OF", "OFFLINE", "ON", "ONLINE", "OPTION", "OR", "ORDER", "PCTFREE", "PRIOR", "PUBLIC", "RAW", "RENAME", "RESOURCE", "REVOKE", "ROW", "ROWID", "ROWNUM",
        "ROWS", "SELECT", "SESSION", "SET", "SHARE", "SIZE", "SMALLINT", "START", "SUCCESSFUL", "SYNONYM", "SYSDATE", "TABLE", "THEN", "TO", "TRIGGER", "UID",
        "UNION", "UNIQUE", "UPDATE", "USER", "VALIDATE", "VALUES", "VARCHAR", "VARCHAR2", "VIEW", "WHENEVER", "WHERE", "WITH",
    };

    /// <summary>A string literal.</summary>
    public static string Literal(string text) => "'" + text.Replace("'", "''", StringComparison.Ordinal) + "'";

    public static async Task<OracleModel> ReadAsync(IDatabaseSession session, string stateSchema, Func<string, bool> excluded, CancellationToken cancellationToken)
    {
        var owner = OracleStateStore.Owner(session);
        var prefix = OracleStateStore.Prefix(stateSchema);
        var state = StateTables.Names.Append(OracleStateStore.LockTable).Select(n => prefix + n.ToUpperInvariant()).ToHashSet(StringComparer.Ordinal);
        bool Skip(string name) => state.Contains(name) || System(name) || excluded($"{owner}.{name}");
        var p = new Dictionary<string, object?> { ["o"] = owner };
        async Task<IReadOnlyList<IReadOnlyDictionary<string, object?>>> Query(string sql) =>
            await session.QueryAsync(sql, p, cancellationToken).ConfigureAwait(false);
        string Local(object? definition) => OracleSchemaInspector.Unqualify(S(definition), owner);

        var model = new OracleModel();

        // Tables (materialized view containers are left to the materialized view).
        var mviews = (await Query("SELECT mview_name AS name FROM all_mviews WHERE owner = :o")).Select(r => S(r["name"])).ToHashSet(StringComparer.Ordinal);
        foreach (var name in mviews.Where(m => !Skip(m)))
        {
            model.Warnings.Add($"Materialized view {name} is not scripted: write its CREATE MATERIALIZED VIEW by hand if it changed.");
        }

        var tableRows = (await Query("""
            SELECT table_name AS t, temporary AS tmp, duration AS dur, iot_type AS iot, partitioned AS part
              FROM all_tables
             WHERE owner = :o AND nested = 'NO' AND dropped = 'NO' AND (iot_type IS NULL OR iot_type = 'IOT')
            """)).Where(r => !Skip(S(r["t"])) && !mviews.Contains(S(r["t"]))).ToList();
        var names = tableRows.Select(r => S(r["t"])).ToHashSet(StringComparer.Ordinal);

        var columns = (await Query("""
            SELECT table_name AS t, column_id AS pos, column_name AS c, data_type AS type, data_length AS len, char_length AS clen,
                   char_used AS cused, data_precision AS prec, data_scale AS scale, nullable AS nul, data_default AS def,
                   virtual_column AS virt, identity_column AS ident, default_on_null AS donull
              FROM all_tab_cols
             WHERE owner = :o AND hidden_column = 'NO'
             ORDER BY table_name, column_id
            """)).Where(r => names.Contains(S(r["t"]))).ToLookup(r => S(r["t"]));
        var identities = (await Query("SELECT table_name AS t, column_name AS c, generation_type AS gen, identity_options AS opts FROM all_tab_identity_cols WHERE owner = :o"))
            .ToDictionary(r => (S(r["t"]), S(r["c"])), r => IdentityClause(S(r["gen"]), S(r["opts"])));

        var consColumns = (await Query("SELECT constraint_name AS name, column_name AS c, position AS pos FROM all_cons_columns WHERE owner = :o"))
            .ToLookup(r => S(r["name"]));
        string Columns(string constraint) => string.Join(", ", consColumns[constraint].OrderBy(c => Convert.ToInt64(c["pos"] ?? 0L, CultureInfo.InvariantCulture)).Select(c => Q(S(c["c"]))));
        var constraintRows = (await Query("""
            SELECT constraint_name AS name, constraint_type AS type, table_name AS t, search_condition_vc AS cond, r_owner AS rowner,
                   r_constraint_name AS rname, delete_rule AS del, deferrable AS defer, deferred AS deferred, status, generated AS gen,
                   index_name AS idx
              FROM all_constraints
             WHERE owner = :o AND constraint_type IN ('P', 'U', 'R', 'C')
            """)).ToList();
        var constraintTables = constraintRows.ToDictionary(r => S(r["name"]), r => S(r["t"]), StringComparer.Ordinal);
        var constraintIndexes = constraintRows.Where(r => S(r["idx"]).Length > 0).Select(r => S(r["idx"])).ToHashSet(StringComparer.Ordinal);
        var constraints = constraintRows.Where(r => names.Contains(S(r["t"]))).ToLookup(r => S(r["t"]));

        var expressions = (await Query("SELECT index_name AS i, column_position AS pos, column_expression AS expr FROM all_ind_expressions WHERE index_owner = :o"))
            .ToDictionary(r => (S(r["i"]), Convert.ToInt64(r["pos"], CultureInfo.InvariantCulture)), r => Local(r["expr"]));
        var indexColumns = (await Query("SELECT index_name AS i, column_name AS c, column_position AS pos, descend FROM all_ind_columns WHERE index_owner = :o"))
            .ToLookup(r => S(r["i"]));
        var indexes = (await Query("""
            SELECT index_name AS i, table_name AS t, index_type AS type, uniqueness AS uniq
              FROM all_indexes
             WHERE owner = :o AND table_owner = :o AND index_type NOT IN ('LOB', 'IOT - TOP') AND generated = 'N'
            """)).Where(r => names.Contains(S(r["t"])) && !constraintIndexes.Contains(S(r["i"]))).ToLookup(r => S(r["t"]));

        var tableComments = (await Query("SELECT table_name AS t, comments AS c FROM all_tab_comments WHERE owner = :o AND comments IS NOT NULL"))
            .ToDictionary(r => S(r["t"]), r => S(r["c"]));
        var columnComments = (await Query("SELECT table_name AS t, column_name AS col, comments AS c FROM all_col_comments WHERE owner = :o AND comments IS NOT NULL"))
            .ToLookup(r => S(r["t"]));

        foreach (var r in tableRows)
        {
            var t = S(r["t"]);
            if (S(r["part"]) == "YES")
            {
                model.Warnings.Add($"Table {t} is partitioned: partitioning is not scripted.");
            }

            var tablePrefix = S(r["tmp"]) == "Y" ? "GLOBAL TEMPORARY " : string.Empty;
            var cols = columns[t].Select(c =>
            {
                var name = S(c["c"]);
                var identity = identities.GetValueOrDefault((t, name));
                var def = identity is null && S(c["def"]) is { Length: > 0 } d && !d.Equals("NULL", StringComparison.OrdinalIgnoreCase) ? Local(d) : null;
                return new OracleColumn(name, ColumnType(c), def, S(c["nul"]) == "Y", S(c["virt"]) == "YES", identity, S(c["donull"]) == "YES");
            }).ToList();

            var cons = new List<OracleConstraint>();
            foreach (var c in constraints[t])
            {
                var kind = S(c["type"]);
                var generated = S(c["gen"]) == "GENERATED NAME";
                var condition = Local(c["cond"]);
                if (kind == "C" && generated && NotNullRegex().IsMatch(condition))
                {
                    continue;
                }

                var name = S(c["name"]);
                var references = kind == "R" ? constraintTables.GetValueOrDefault(S(c["rname"])) : null;
                var body = kind switch
                {
                    "P" => $"PRIMARY KEY ({Columns(name)})",
                    "U" => $"UNIQUE ({Columns(name)})",
                    "R" => $"FOREIGN KEY ({Columns(name)}) REFERENCES {(S(c["rowner"]) == owner ? string.Empty : Q(S(c["rowner"])) + ".")}{Q(references ?? S(c["rname"]))} ({Columns(S(c["rname"]))}){(S(c["del"]) is "CASCADE" or "SET NULL" ? " ON DELETE " + S(c["del"]) : string.Empty)}",
                    _ => $"CHECK ({condition})",
                };
                if (S(c["defer"]) == "DEFERRABLE")
                {
                    body += $" DEFERRABLE INITIALLY {S(c["deferred"])}";
                }

                if (S(c["status"]) == "DISABLED")
                {
                    body += " DISABLE";
                }

                cons.Add(new OracleConstraint(name, generated, kind, body, S(c["rowner"]) == owner || kind != "R" ? references : null));
            }

            var idx = indexes[t].Select(i =>
            {
                var index = S(i["i"]);
                var parts = indexColumns[index].OrderBy(c => Convert.ToInt64(c["pos"], CultureInfo.InvariantCulture)).Select(c =>
                    (expressions.TryGetValue((index, Convert.ToInt64(c["pos"], CultureInfo.InvariantCulture)), out var e) ? e : Q(S(c["c"])))
                    + (S(c["descend"]) == "DESC" ? " DESC" : string.Empty));
                var kind = S(i["uniq"]) == "UNIQUE" ? "UNIQUE " : S(i["type"]).StartsWith("BITMAP", StringComparison.Ordinal) ? "BITMAP " : string.Empty;
                return new OracleIndex(index, $"CREATE {kind}INDEX {Q(index)} ON {Q(t)} ({string.Join(", ", parts)})");
            }).ToList();

            model.Tables[t] = new OracleTable(t, tablePrefix, cols, cons, idx, tableComments.GetValueOrDefault(t),
                columnComments[t].ToDictionary(c => S(c["col"]), c => S(c["c"]), StringComparer.Ordinal));
        }

        // Views, with their column names (the dictionary keeps only the query).
        var viewColumns = (await Query("SELECT table_name AS t, column_name AS c FROM all_tab_columns WHERE owner = :o ORDER BY table_name, column_id")).ToLookup(r => S(r["t"]));
        foreach (var r in await Query("SELECT view_name AS name, text, read_only AS ro FROM all_views WHERE owner = :o"))
        {
            var name = S(r["name"]);
            if (!Skip(name))
            {
                var list = string.Join(", ", viewColumns[name].Select(c => Q(S(c["c"]))));
                var create = $"CREATE OR REPLACE FORCE VIEW {Q(name)} ({list}) AS\n{Local(r["text"]).Trim()}{(S(r["ro"]) == "Y" ? "\nWITH READ ONLY" : string.Empty)}";
                model.Objects[$"view {name}"] = new OracleObject("view", name, create);
            }
        }

        foreach (var r in await Query("""
            SELECT sequence_name AS name, min_value AS lo, max_value AS hi, increment_by AS inc, cycle_flag AS cyc, order_flag AS ord,
                   cache_size AS cache, last_number AS next
              FROM all_sequences
             WHERE sequence_owner = :o AND sequence_name NOT LIKE 'ISEQ$$%'
            """))
        {
            var name = S(r["name"]);
            if (!Skip(name))
            {
                var options = SequenceOptions(r);
                model.Objects[$"sequence {name}"] = new OracleObject("sequence", name, $"CREATE SEQUENCE {Q(name)} START WITH {S(r["next"])} {options}") { };
                model.SequenceOptionsByName[name] = options;
            }
        }

        foreach (var r in await Query("SELECT synonym_name AS name, table_owner AS towner, table_name AS t, db_link AS link FROM all_synonyms WHERE owner = :o"))
        {
            var name = S(r["name"]);
            if (!Skip(name))
            {
                var target = (S(r["towner"]) == owner ? string.Empty : Q(S(r["towner"])) + ".") + Q(S(r["t"])) + (S(r["link"]) is { Length: > 0 } link ? "@" + link : string.Empty);
                model.Objects[$"synonym {name}"] = new OracleObject("synonym", name, $"CREATE OR REPLACE SYNONYM {Q(name)} FOR {target}");
            }
        }

        // PL/SQL: the source as written, after CREATE OR REPLACE.
        var triggerTables = (await Query("SELECT trigger_name AS name, table_name AS t FROM all_triggers WHERE owner = :o")).ToDictionary(r => S(r["name"]), r => S(r["t"]), StringComparer.Ordinal);
        var source = new Dictionary<(string Type, string Name), StringBuilder>();
        foreach (var r in await Query("""
            SELECT type, name, text
              FROM all_source
             WHERE owner = :o AND type IN ('PROCEDURE', 'FUNCTION', 'PACKAGE', 'PACKAGE BODY', 'TRIGGER', 'TYPE', 'TYPE BODY')
             ORDER BY type, name, line
            """))
        {
            var key = (S(r["type"]), S(r["name"]));
            if (!source.TryGetValue(key, out var text))
            {
                source[key] = text = new StringBuilder();
            }

            text.Append(r["text"] as string);
        }

        foreach (var ((type, name), text) in source)
        {
            if (Skip(name))
            {
                continue;
            }

            var body = OracleSchemaInspector.Unqualify(text.ToString().Replace("\r\n", "\n", StringComparison.Ordinal).TrimEnd(), owner);
            var kind = type.ToLowerInvariant();
            model.Objects[$"{kind} {name}"] = new OracleObject(kind, name, "CREATE OR REPLACE " + body, kind == "trigger" ? triggerTables.GetValueOrDefault(name) : null, PlSql: true);
        }

        return model;
    }

    /// <summary>A sequence's options other than where it starts: INCREMENT BY, MINVALUE, MAXVALUE, CYCLE, ORDER, CACHE.</summary>
    public Dictionary<string, string> SequenceOptionsByName { get; } = new(StringComparer.Ordinal);

    private static string SequenceOptions(IReadOnlyDictionary<string, object?> r) =>
        $"INCREMENT BY {S(r["inc"])} MINVALUE {S(r["lo"])} MAXVALUE {S(r["hi"])} {(S(r["cyc"]) == "Y" ? "CYCLE" : "NOCYCLE")} {(S(r["ord"]) == "Y" ? "ORDER" : "NOORDER")} {(S(r["cache"]) is "0" or "" ? "NOCACHE" : "CACHE " + S(r["cache"]))}";

    /// <summary>GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) from ALL_TAB_IDENTITY_COLS.</summary>
    private static string IdentityClause(string generation, string options)
    {
        string Option(string key) => Regex.Match(options, key + @":\s*(-?\d+)") is { Success: true } m ? m.Groups[1].Value : string.Empty;
        var start = Option("START WITH");
        var increment = Option("INCREMENT BY");
        var extra = start is "" or "1" && increment is "" or "1" ? string.Empty : $" (START WITH {start} INCREMENT BY {increment})";
        return $"GENERATED {generation} AS IDENTITY{extra}";
    }

    private static string ColumnType(IReadOnlyDictionary<string, object?> r)
    {
        var type = S(r["type"]);
        string N(string key) => S(r[key]);
        return type switch
        {
            "VARCHAR2" or "CHAR" => $"{type}({N("clen")} {(N("cused") == "C" ? "CHAR" : "BYTE")})",
            "NVARCHAR2" or "NCHAR" => $"{type}({N("clen")})",
            "RAW" => $"RAW({N("len")})",
            "NUMBER" when N("prec").Length > 0 => N("scale") is { Length: > 0 } s && s != "0" ? $"NUMBER({N("prec")},{s})" : $"NUMBER({N("prec")})",
            "NUMBER" when N("scale") == "0" => "INTEGER",
            "FLOAT" => $"FLOAT({N("prec")})",
            _ => type,
        };
    }

    private static bool System(string name) =>
        name.StartsWith("BIN$", StringComparison.Ordinal) || name.StartsWith("SYS_", StringComparison.Ordinal) || name.StartsWith("ISEQ$$", StringComparison.Ordinal)
        || name.StartsWith("MLOG$_", StringComparison.Ordinal) || name.StartsWith("RUPD$_", StringComparison.Ordinal) || name.StartsWith("DR$", StringComparison.Ordinal);

    private static string S(object? value) => value switch
    {
        null => string.Empty,
        _ => (Convert.ToString(value, CultureInfo.InvariantCulture) ?? string.Empty).Replace("\r\n", "\n", StringComparison.Ordinal).Trim(),
    };

    [GeneratedRegex(@"\A[A-Z][A-Z0-9_$#]*\z")]
    private static partial Regex PlainNameRegex();

    [GeneratedRegex(@"\A""[^""]+""\s+IS\s+NOT\s+NULL\z", RegexOptions.IgnoreCase)]
    private static partial Regex NotNullRegex();
}
