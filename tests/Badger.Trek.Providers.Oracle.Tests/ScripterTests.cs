using Badger.Trek.Core.Configuration;
using Badger.Trek.Core.Providers;
using Badger.Trek.Providers.Oracle.Scripting;
using Oracle.ManagedDataAccess.Client;
using Xunit.Abstractions;

namespace Badger.Trek.Providers.Oracle.Tests;

/// <summary>
/// 'trek add --from-diff' on Oracle: each scenario builds schema A in one schema and B in another, scripts the
/// difference, and checks that the deploy script turns A into B (same fingerprint) and the revert script turns it back.
/// </summary>
[Collection("oracle")]
public sealed class ScripterTests(OracleFixture fixture, ITestOutputHelper output)
{
    private readonly OracleProvider provider = new();

    private const string Base = """
        CREATE TABLE customer (
          id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          email VARCHAR2(200 CHAR) NOT NULL,
          name VARCHAR2(100 CHAR),
          CONSTRAINT ux_email UNIQUE (email)
        );
        COMMENT ON TABLE customer IS 'people who buy';
        CREATE TABLE orders (
          id NUMBER(10) NOT NULL PRIMARY KEY,
          customer_id NUMBER(10) NOT NULL,
          total NUMBER(12,2) DEFAULT 0 NOT NULL,
          note VARCHAR2(50 CHAR),
          CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
          CONSTRAINT ck_total CHECK (total >= 0)
        );
        CREATE INDEX ix_customer ON orders (customer_id);
        INSERT INTO customer (email, name) VALUES ('a@example.com', 'Ann');
        INSERT INTO orders (id, customer_id, total, note) VALUES (1, 1, 10, 'first');
        """;

    private async Task<(SchemaScript Script, string Before, string After)> RoundTripAsync(string a, string b, IReadOnlyList<string>? repeatables = null)
    {
        Skip.If(fixture.AdminConnectionString is null, fixture.UnavailableReason);
        await using var dbA = await fixture.CreateSchemaAsync();
        await using var dbB = await fixture.CreateSchemaAsync();
        await using var sa = await provider.OpenSessionAsync(dbA.Profile, SessionContext.Empty, CancellationToken.None);
        await using var sb = await provider.OpenSessionAsync(dbB.Profile, SessionContext.Empty, CancellationToken.None);
        await RunAsync(sa, a);
        await RunAsync(sb, b);
        var before = await provider.Schema.CaptureAsync(sa, "trek", CancellationToken.None);
        var after = await provider.Schema.CaptureAsync(sb, "trek", CancellationToken.None);
        var options = new SchemaScriptOptions { StateSchema = "trek", RepeatableScripts = repeatables ?? [] };

        var script = await provider.Scripter.ScriptAsync(sa, sb, options, CancellationToken.None);
        output.WriteLine("-- deploy\n" + script.Deploy + "\n-- revert\n" + script.Revert + "\n-- summary\n" + string.Join("\n", script.Summary) + "\n-- warnings\n" + string.Join("\n", script.Warnings));

        await RunAsync(sa, script.Deploy);
        if (repeatables is null)
        {
            Assert.Equal(after, await provider.Schema.CaptureAsync(sa, "trek", CancellationToken.None));
        }

        await RunAsync(sa, script.Revert);
        Assert.Equal(before, await provider.Schema.CaptureAsync(sa, "trek", CancellationToken.None));

        var again = await provider.Scripter.ScriptAsync(sa, sa, options, CancellationToken.None);
        Assert.True(again.IsEmpty, again.Deploy);
        return (script, before, after);
    }

    private async Task RunAsync(IDatabaseSession session, string script)
    {
        foreach (var batch in provider.Parser.Split(script))
        {
            await session.ExecuteAsync(batch.Text, null, CancellationToken.None);
        }
    }

    [SkippableFact]
    public async Task Columns_are_added_dropped_renamed_retyped_and_changed()
    {
        var (script, _, _) = await RoundTripAsync(Base, Base
            .Replace("  name VARCHAR2(100 CHAR),\n", "  display_name VARCHAR2(100 CHAR),\n", StringComparison.Ordinal)
            .Replace("  total NUMBER(12,2) DEFAULT 0 NOT NULL,\n  note VARCHAR2(50 CHAR),", "  total NUMBER(12,2) DEFAULT 1 NOT NULL,\n  note VARCHAR2(80 CHAR) NOT NULL,\n  shipped DATE,", StringComparison.Ordinal)
            .Replace("COMMENT ON TABLE customer IS 'people who buy';", "COMMENT ON TABLE customer IS 'people who buy things';\nCOMMENT ON COLUMN customer.email IS 'login';", StringComparison.Ordinal)
            .Replace("INSERT INTO customer (email, name)", "INSERT INTO customer (email, display_name)", StringComparison.Ordinal));

        Assert.Contains("ALTER TABLE CUSTOMER RENAME COLUMN NAME TO DISPLAY_NAME;", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("ALTER TABLE ORDERS ADD (SHIPPED DATE);", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("ALTER TABLE ORDERS MODIFY (TOTAL DEFAULT 1);", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("ALTER TABLE ORDERS MODIFY (NOTE VARCHAR2(80 CHAR) NOT NULL);", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("COMMENT ON COLUMN CUSTOMER.EMAIL IS 'login';", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("ALTER TABLE ORDERS DROP COLUMN SHIPPED;", script.Revert, StringComparison.Ordinal);
        Assert.Contains("ALTER TABLE ORDERS MODIFY (NOTE VARCHAR2(50 CHAR) NULL);", script.Revert, StringComparison.Ordinal);
        Assert.Contains(script.Warnings, w => w.Contains("NOTE becomes NOT NULL", StringComparison.Ordinal));
        Assert.True(script.DataLoss);
    }

    [SkippableFact]
    public async Task Constraints_and_indexes_are_dropped_and_added()
    {
        var (script, _, _) = await RoundTripAsync(Base, Base
            .Replace("CONSTRAINT ck_total CHECK (total >= 0)", "CONSTRAINT ck_total CHECK (total >= 1),\n  CONSTRAINT ux_orders_note UNIQUE (customer_id, note)", StringComparison.Ordinal)
            .Replace("CREATE INDEX ix_customer ON orders (customer_id);", "CREATE INDEX ix_customer ON orders (customer_id, total DESC);\nCREATE INDEX ix_note_lower ON orders (LOWER(note));", StringComparison.Ordinal));

        Assert.Contains("ALTER TABLE ORDERS DROP CONSTRAINT CK_TOTAL;", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("ALTER TABLE ORDERS ADD CONSTRAINT CK_TOTAL CHECK (total >= 1);", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("DROP INDEX IX_CUSTOMER;", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("CREATE INDEX IX_NOTE_LOWER ON ORDERS (LOWER(\"NOTE\"));", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("+ unique ORDERS.UX_ORDERS_NOTE", script.Summary);
    }

    [SkippableFact]
    public async Task New_tables_with_foreign_keys_in_a_cycle_and_a_dropped_referenced_table()
    {
        var (script, _, _) = await RoundTripAsync(Base, Base
            .Replace("CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customer (id),", string.Empty, StringComparison.Ordinal)
            .Replace("INSERT INTO customer", """
                CREATE TABLE a_node (id NUMBER PRIMARY KEY, b_id NUMBER);
                CREATE TABLE b_node (id NUMBER PRIMARY KEY, a_id NUMBER REFERENCES a_node (id) ON DELETE CASCADE);
                ALTER TABLE a_node ADD CONSTRAINT fk_a_b FOREIGN KEY (b_id) REFERENCES b_node (id);
                INSERT INTO customer
                """, StringComparison.Ordinal));

        Assert.Contains("CREATE TABLE A_NODE", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("ALTER TABLE A_NODE ADD CONSTRAINT FK_A_B FOREIGN KEY (B_ID) REFERENCES B_NODE (ID);", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("ALTER TABLE B_NODE ADD FOREIGN KEY (A_ID) REFERENCES A_NODE (ID) ON DELETE CASCADE;", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("ALTER TABLE ORDERS DROP CONSTRAINT FK_ORDERS_CUSTOMER;", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("DROP TABLE B_NODE CASCADE CONSTRAINTS PURGE;", script.Revert, StringComparison.Ordinal);
        Assert.True(script.DataLoss || script.Revert.Contains("DROP TABLE", StringComparison.Ordinal));
    }

    [SkippableFact]
    public async Task Views_sequences_synonyms_and_plsql_are_created_again_and_repeatables_are_left_alone()
    {
        const string Code = """
            CREATE SEQUENCE invoice_no START WITH 100 INCREMENT BY 1 NOCACHE;
            CREATE OR REPLACE VIEW big_orders AS SELECT o.id, c.email FROM orders o JOIN customer c ON c.id = o.customer_id WHERE o.total > 100;
            CREATE OR REPLACE PACKAGE shop AS
              FUNCTION order_count(p_customer NUMBER) RETURN NUMBER;
            END shop;
            /
            CREATE OR REPLACE PACKAGE BODY shop AS
              FUNCTION order_count(p_customer NUMBER) RETURN NUMBER IS
                v NUMBER;
              BEGIN
                SELECT COUNT(*) INTO v FROM orders WHERE customer_id = p_customer;
                RETURN v;
              END;
            END shop;
            /
            CREATE OR REPLACE TRIGGER orders_bi BEFORE INSERT ON orders FOR EACH ROW
            BEGIN
              :NEW.note := NVL(:NEW.note, 'none');
            END;
            /
            """;
        var changed = Code
            .Replace("INCREMENT BY 1 NOCACHE", "INCREMENT BY 5 NOCACHE", StringComparison.Ordinal)
            .Replace("o.total > 100", "o.total > 500", StringComparison.Ordinal)
            .Replace("RETURN v;", "RETURN v + 0;", StringComparison.Ordinal)
            + "\n" + """
            CREATE OR REPLACE PROCEDURE close_order(p_id NUMBER) AS
            BEGIN
              UPDATE orders SET note = 'closed' WHERE id = p_id;
            END;
            /
            CREATE SYNONYM purchases FOR orders;
            """;
        var (script, _, _) = await RoundTripAsync(Base + "\n" + Code, Base + "\n" + changed);

        Assert.Contains("ALTER SEQUENCE INVOICE_NO INCREMENT BY 5", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("CREATE OR REPLACE FORCE VIEW BIG_ORDERS", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("CREATE OR REPLACE PACKAGE BODY shop", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("END shop;\n/", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("CREATE OR REPLACE PROCEDURE close_order", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("CREATE OR REPLACE SYNONYM PURCHASES FOR ORDERS;", script.Deploy, StringComparison.Ordinal);
        Assert.Contains("DROP PROCEDURE CLOSE_ORDER;", script.Revert, StringComparison.Ordinal);
        Assert.Contains("DROP SYNONYM PURCHASES;", script.Revert, StringComparison.Ordinal);
        Assert.DoesNotContain("orders_bi", script.Deploy, StringComparison.OrdinalIgnoreCase);

        // Objects that repeatable scripts create are theirs.
        var (owned, _, _) = await RoundTripAsync(Base + "\n" + Code, Base + "\n" + changed, ["CREATE OR REPLACE VIEW big_orders AS SELECT 1 AS id FROM dual;", "create or replace package body Shop as end;"]);
        Assert.DoesNotContain("BIG_ORDERS", owned.Deploy, StringComparison.Ordinal);
        Assert.DoesNotContain("PACKAGE BODY", owned.Deploy, StringComparison.Ordinal);
        Assert.Contains("close_order", owned.Deploy, StringComparison.Ordinal);
    }

    [SkippableFact]
    public async Task A_shadow_schema_is_created_and_dropped()
    {
        Skip.If(fixture.AdminConnectionString is null, fixture.UnavailableReason);
        var server = new DeploymentEnvironment { Name = "server", ConnectionString = fixture.AdminConnectionString };
        string user;
        await using (var shadow = await provider.ScratchDatabases.CreateAsync(server, SessionContext.Empty, keep: false, CancellationToken.None))
        {
            user = shadow.Environment.User!;
            Assert.StartsWith("TREK_SHADOW_", user, StringComparison.Ordinal);
            await using var session = await provider.OpenSessionAsync(shadow.Environment, SessionContext.Empty, CancellationToken.None);
            await RunAsync(session, Base);
            Assert.Contains("table|ORDERS|", await provider.Schema.CaptureAsync(session, "trek", CancellationToken.None), StringComparison.Ordinal);
        }

        await using var admin = new OracleConnection(fixture.AdminConnectionString);
        await admin.OpenAsync();
        await using var count = new OracleCommand($"SELECT COUNT(*) FROM all_users WHERE username = '{user}'", admin);
        Assert.Equal(0m, (decimal)(await count.ExecuteScalarAsync())!);
    }

    [Fact]
    public void Repeatable_scripts_own_the_objects_they_create()
    {
        var owned = OracleScripter.OwnedObjects(["CREATE OR REPLACE EDITIONABLE PACKAGE BODY app.Shop AS END;", "create or replace force view \"Mixed\" as select 1 x from dual;", "CREATE OR REPLACE TRIGGER t_bi BEFORE INSERT ON t FOR EACH ROW BEGIN NULL; END;"]);
        Assert.Equal(["package body SHOP", "trigger T_BI", "view Mixed"], owned.Order(StringComparer.Ordinal));
    }
}
