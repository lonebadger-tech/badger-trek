CREATE SEQUENCE ticket_no START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE TABLE customers (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR2(100 CHAR) NOT NULL,
    email VARCHAR2(320 CHAR),
    tier VARCHAR2(10 CHAR) DEFAULT 'free' NOT NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL,
    notes CLOB,
    joined TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT customers_pk PRIMARY KEY (id),
    CONSTRAINT customers_email UNIQUE (email),
    CONSTRAINT customers_tier CHECK (tier IN ('free', 'pro', 'enterprise')),
    CONSTRAINT customers_active CHECK (active IN (0, 1))
);
COMMENT ON TABLE customers IS 'people who buy things';

CREATE TABLE orders (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    customer_id NUMBER(10) NOT NULL,
    ticket NUMBER(19) DEFAULT ticket_no.NEXTVAL NOT NULL,
    total NUMBER(10,2) DEFAULT 0 NOT NULL,
    total_with_tax NUMBER(12,2) GENERATED ALWAYS AS (total * 1.2) VIRTUAL,
    status VARCHAR2(20 CHAR) DEFAULT 'open' NOT NULL,
    placed_at DATE DEFAULT SYSDATE NOT NULL,
    shipped_at TIMESTAMP(6) WITH TIME ZONE,
    receipt BLOB,
    CONSTRAINT orders_pk PRIMARY KEY (id),
    CONSTRAINT orders_customer_fk FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT orders_total_positive CHECK (total >= 0)
);
CREATE INDEX orders_customer ON orders (customer_id, placed_at);
CREATE INDEX customers_lower_name ON customers (LOWER(name));

CREATE OR REPLACE VIEW customer_totals AS
SELECT c.id, c.name, COUNT(o.id) AS orders, NVL(SUM(o.total), 0) AS spent,
       DECODE(c.tier, 'pro', 'yes', 'enterprise', 'yes', 'no') AS paying
FROM customers c LEFT JOIN orders o ON o.customer_id = c.id
GROUP BY c.id, c.name, c.tier;

CREATE OR REPLACE PROCEDURE close_order(p_id NUMBER) AS
BEGIN
  UPDATE orders SET status = 'closed' WHERE id = p_id;
END;
